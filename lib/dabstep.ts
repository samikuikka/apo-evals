/**
 * dabstep — the benchmark's scorer, ported once, shared by every generated
 * task in tasks/dabstep/.
 *
 * The answer matcher is a faithful port of DABstep's official
 * `question_scorer` (dabstep_benchmark/evaluation/scorer.py in the
 * adyen/DABstep leaderboard space at the pinned revision), so apo grades
 * answers exactly the way the benchmark does — no LLM judge on answers
 * the benchmark already scores deterministically. Two deliberate
 * deviations, both stricter than upstream and noted where they occur:
 * the fuzzy SequenceMatcher>0.95 fallback is dropped, and numeric
 * extraction keeps the sign (upstream's regex drops it, which would
 * score a wrong-signed delta as correct).
 *
 * Task files are GENERATED by scripts/convert-dabstep.ts. They are plain
 * apo tasks — flat, inline checks — and this file only supplies the
 * `dabstepAnswer` matcher plus the conversion helpers the converter needs.
 */
import { satisfies } from "@apo-ai/sdk/agent-task";
import type { Matcher } from "@apo-ai/sdk/agent-task";
import { readFile } from "node:fs/promises";

/** One record of data/dabstep/tasks/dev.jsonl (pinned revision). */
export type DabstepCase = {
  task_id: string;
  question: string;
  guidelines: string;
  level: string;
  answer: string;
};

export async function loadDevCases(devJsonlPath: string): Promise<DabstepCase[]> {
  const text = await readFile(devJsonlPath, "utf8");
  return text
    .split("\n")
    .filter((line) => line.trim().length > 0)
    .map((line) => JSON.parse(line) as DabstepCase);
}

/** The answer shapes present in the dev split; drives fixtures and wording. */
export type AnswerShape = "string" | "choice" | "numeric" | "list" | "not-applicable";

export function classifyAnswer(answer: string): AnswerShape {
  const a = answer.trim().toLowerCase();
  if (a === "not applicable") return "not-applicable";
  if (/^[a-e]\.\s?\S+$/i.test(answer.trim())) return "choice";
  if (/^[+-]?\d+(?:\.\d+)?$/.test(answer.trim())) return "numeric";
  if (answer.includes(",")) return "list";
  return "string";
}

// ── Port of DABstep question_scorer ────────────────────────────────────────
// Source: adyen/DABstep leaderboard space, dabstep_benchmark/evaluation/
// scorer.py @ the revision pinned in scripts/fetch-data.sh. Branch order and
// tolerances mirror the original; see the deviations noted inline.

/** Upstream `is_numeric_with_commas` — thousands separators or plain decimals. */
function isNumericWithCommas(value: string): boolean {
  const pattern =
    /^\$?(?:\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+[.,]\d+)$/;
  return pattern.test(value.trim());
}

/**
 * Upstream `extract_numeric`, with one deviation: the leading sign is kept.
 * (Upstream's regex drops it, so a delta of -0.95 would match +0.95 —
 * clearly wrong for the signed-delta questions in the dev split.)
 */
function extractNumeric(value: string): number | null {
  const cleaned = value.replace(/,/g, "").replace(/\$/g, "");
  const match = cleaned.match(/([+-]?(?:\d*\.\d+|\d+\.?\d*))%?/);
  if (!match) return null;
  const n = Number.parseFloat(match[1]);
  return Number.isFinite(n) ? n : null;
}

/** math.isclose(rel_tol=1e-4, abs_tol=1e-4), standard formulation. */
function isClose(a: number, b: number): boolean {
  return Math.abs(a - b) <= Math.max(1e-4, 1e-4 * Math.max(Math.abs(a), Math.abs(b)));
}

function decimalsOf(n: number): number {
  const s = String(n);
  const dot = s.indexOf(".");
  return dot === -1 ? 0 : s.length - dot - 1;
}

/** Upstream `compare_numeric`: exact, then <1 isclose, then shared rounding, then isclose. */
function compareNumeric(a: number, b: number): boolean {
  if (a === b) return true;
  if (a < 1 && b < 1) return isClose(a, b);
  const roundTo = Math.min(decimalsOf(a), decimalsOf(b));
  const factor = 10 ** roundTo;
  if (Math.round(a * factor) / factor === Math.round(b * factor) / factor) return true;
  return isClose(a, b);
}

/**
 * Upstream `compare_strings`: punctuation-stripped equality, then a subset
 * rule when one side is a single word. The final SequenceMatcher>0.95
 * fallback is deliberately NOT ported — this repo does not accept
 * near-miss strings on questions whose answers are exact by construction.
 */
function compareStrings(a: string, b: string): boolean {
  const clean = (s: string) => s.replace(/[^\w]/g, "");
  if (clean(a) === clean(b)) return true;
  const words1 = a.match(/\b\w+\b/g) ?? [];
  const words2 = b.match(/\b\w+\b/g) ?? [];
  if ((words1.length === 1 || words2.length === 1) && words1.length > 0 && words2.length > 0) {
    return words1.every((w) => words2.includes(w)) || words2.every((w) => words1.includes(w));
  }
  return false;
}

/** Upstream `compare_lists`: order-insensitive, then per-item question_scorer. */
function compareLists(a: string, b: string): boolean {
  const items = (s: string) =>
    s
      .trim()
      .replace(/^\[/, "")
      .replace(/\]$/, "")
      .split(/[,;]/)
      .map((item) => item.trim())
      .filter((item) => item.length > 0);
  const items1 = items(a).sort();
  const items2 = items(b).sort();
  if (items1.length !== items2.length) return false;
  if (items1.every((item, i) => item === items2[i])) return true;
  return items1.every((item, i) => questionScorer(item, items2[i]));
}

/** The benchmark's verdict for one answer, ported 1:1 from question_scorer. */
export function questionScorer(given: string, expected: string): boolean {
  const givenNorm = given.trim().toLowerCase();
  const expectedNorm = expected.trim().toLowerCase();

  if (isNumericWithCommas(givenNorm) || isNumericWithCommas(expectedNorm)) {
    const n1 = extractNumeric(givenNorm);
    const n2 = extractNumeric(expectedNorm);
    return n1 !== null && n2 !== null ? compareNumeric(n1, n2) : false;
  }

  if (
    givenNorm.includes(";") ||
    expectedNorm.includes(";") ||
    givenNorm.includes(",") ||
    expectedNorm.includes(",")
  ) {
    return compareLists(givenNorm, expectedNorm);
  }

  const n1 = extractNumeric(givenNorm);
  const n2 = extractNumeric(expectedNorm);
  if (n1 !== null && n2 !== null) return compareNumeric(n1, n2);

  return compareStrings(givenNorm, expectedNorm);
}

/** Describe how the ported scorer will compare this shape — used in check labels. */
export function scoringNote(expected: string): string {
  switch (classifyAnswer(expected)) {
    case "numeric":
      return "numeric compare with the benchmark's tolerance (rel/abs 1e-4)";
    case "list":
      return "order-insensitive list compare, item-by-item under the same scorer";
    case "not-applicable":
      return "normalized string compare";
    default:
      return "normalized string compare";
  }
}

/** The benchmark's verdict as a native apo matcher, for use in `t.check`. */
export function dabstepAnswer(expected: string): Matcher<string> {
  const shown = expected.length > 60 ? `${expected.slice(0, 57)}...` : expected;
  return satisfies(
    (given: string) => questionScorer(given, expected),
    `matches DABstep ground truth "${shown}" (${scoringNote(expected)})`,
  );
}
